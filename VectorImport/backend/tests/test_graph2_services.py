class TestReflectionService:

    def test_reflect_passes_valid_mitigations(self, intelligence_alpha, mock_llm):
        summary = ContextBuilderService(llm_service=mock_llm).build_context(intelligence_alpha)
        risks = RiskAssessmentService(llm_service=mock_llm).assess_risks(intelligence_alpha)
        mitigations = MitigationPlanningService(llm_service=mock_llm).plan_mitigations(risks)

        service = ReflectionService(llm_service=mock_llm)
        feedback = service.reflect(summary, risks, mitigations, retry_count=0)
        assert isinstance(feedback, ReflectionFeedback)
        assert feedback.passed is True
        assert feedback.grounding_score >= 0.8

    def test_reflect_triggers_retry_on_forced_flag(self, mock_llm):
        service = ReflectionService(llm_service=mock_llm)
        feedback = service.reflect(
            context_summary="FORCE_REFLECTION_RETRY test summary",
            risks=[],
            mitigations=[],
            retry_count=0,
        )
        assert feedback.passed is False


class TestRiskReportBuilderService:

    def test_build_report_returns_risk_assessment_report(self, intelligence_alpha, mock_llm):
        summary = ContextBuilderService(llm_service=mock_llm).build_context(intelligence_alpha)
        evidence = EvidenceCollectorService().collect_evidence(intelligence_alpha)
        risks = RiskAssessmentService(llm_service=mock_llm).assess_risks(intelligence_alpha)
        mitigations = MitigationPlanningService(llm_service=mock_llm).plan_mitigations(risks)
        feedback = ReflectionService(llm_service=mock_llm).reflect(summary, risks, mitigations)

        service = RiskReportBuilderService(llm_service=mock_llm)
        report = service.build_report(
            intelligence_alpha, summary, risks, evidence, mitigations, feedback
        )

        assert isinstance(report, RiskAssessmentReport)
        assert report.project_id == "PROG-ALPHA-2026"
        assert len(report.categorized_risks) > 0
        assert len(report.mitigations) > 0

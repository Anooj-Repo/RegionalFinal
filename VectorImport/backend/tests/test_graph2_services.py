class MockLLMService(LLMService):
    """Mock LLMService for offline test suites."""

    def __init__(self):
        self.provider = "openai"
        self.api_key = "sk-test-mock-key"
        self.model_name = "gpt-4o-mini"

    def validate_configuration(self) -> None:
        pass

    def invoke_text(self, prompt: str) -> str:
        return "Executive summary generated by Mock LLM for project analysis."

    def invoke_structured(self, prompt: str, response_model: type):
        if response_model.__name__ == "DecisionPlanOutput":
            return DecisionPlanOutput(priorities=["Unblock vendor deliverables", "Mitigate critical risks"])
        elif response_model.__name__ == "RiskAssessmentOutput":
            return RiskAssessmentOutput(
                risks=[
                    CategorizedRisk(
                        risk_id="risk_llm_1",
                        category="vendor_delivery",
                        title="CloudSphere Vendor Delay",
                        description="API Gateway delivery missed by vendor.",
                        probability="high",
                        impact="critical",
                        risk_score=90.0,
                    )
                ]
            )
        elif response_model.__name__ == "MitigationPlanningOutput":
            return MitigationPlanningOutput(
                mitigations=[
                    MitigationPlan(
                        mitigation_id="mit_llm_1",
                        target_risk_id="risk_llm_1",
                        action_title="Invoke Vendor SLA Penalties",
                        action_description="Formal executive escalation.",
                        owner="Program Manager",
                        due_date="2026-08-31",
                        cost_estimate="Low",
                        expected_impact="High Risk Reduction",
                    )
                ]
            )
        elif response_model.__name__ == "ReflectionFeedback":
            if "FORCE_REFLECTION_RETRY" in prompt:
                return ReflectionFeedback(
                    passed=False,
                    grounding_score=0.5,
                    consistency_score=0.5,
                    unsupported_claims=["Forced retry claim"],
                    reflection_notes="Audit failed — retry needed.",
                )
            return ReflectionFeedback(
                passed=True,
                grounding_score=0.95,
                consistency_score=0.95,
                unsupported_claims=[],
                reflection_notes="Grounded by LLM audit.",
            )
        return response_model()



class TestLLMServiceValidation:

    def test_missing_api_key_raises_llm_configuration_error(self):
        with pytest.raises(LLMConfigurationError) as exc_info:
            LLMService(provider="openai", api_key="")
        assert "LLM_API_KEY" in str(exc_info.value)

    def test_placeholder_api_key_raises_llm_configuration_error(self):
        with pytest.raises(LLMConfigurationError) as exc_info:
            LLMService(provider="openai", api_key="placeholder")
        assert "LLM_API_KEY" in str(exc_info.value)


